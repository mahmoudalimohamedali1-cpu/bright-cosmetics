export function districtsOf(governorateId: string): District[] {
  return DISTRICTS[governorateId] ?? []
}

/** Display name of an order's district, or undefined when none (or "other") was chosen. */
export function districtName(governorateId: string, districtId: string | undefined): Bi | undefined {
  if (!districtId || districtId === OTHER_DISTRICT) return undefined
  const d = districtsOf(governorateId).find((x) => x.id === districtId)
  return d ? { ar: d.ar, en: d.en } : undefined
}

export function isDistrictOf(governorateId: string, districtId: string): boolean {
  return districtId === OTHER_DISTRICT || districtsOf(governorateId).some((x) => x.id === districtId)
}

/** "Dokki" / "الدقي" for an order, or '' when it has no listed district. */
export function districtLabel(governorateId: string, districtId: string | undefined, lang: 'ar' | 'en'): string {
  const d = districtName(governorateId, districtId)
  return d ? d[lang] : ''
}
