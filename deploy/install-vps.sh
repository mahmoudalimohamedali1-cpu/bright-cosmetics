#!/usr/bin/env bash
# Bright: install or update on an Ubuntu/Debian VPS. Run as root:
#   curl -fsSL https://raw.githubusercontent.com/mahmoudalimohamedali1-cpu/bright-cosmetics/main/deploy/install-vps.sh -o install.sh
#   sudo bash install.sh your-domain.com
# First run asks for the admin email and password on the server itself (nothing
# is stored in git), unless /etc/bright.env already exists. Re-run to update to
# the latest code: the database in /var/lib/bright and the certificate are kept.
#
# Works directly or behind Cloudflare (proxied, SSL mode "Full (strict)").
set -euo pipefail

DOMAIN="${1:-}"
APP=/opt/bright
DATA=/var/lib/bright
ENVF=/etc/bright.env
REPO=https://github.com/mahmoudalimohamedali1-cpu/bright-cosmetics.git
WEBROOT=/var/www/certbot

[ "$(id -u)" = 0 ] || { echo "Run as root (sudo)."; exit 1; }

export DEBIAN_FRONTEND=noninteractive
apt-get update -y
apt-get install -y curl git nginx ca-certificates ufw certbot

# Small servers (1 GB) run out of memory during the build without swap.
if ! swapon --show | grep -q . ; then
  fallocate -l 2G /swapfile && chmod 600 /swapfile && mkswap /swapfile >/dev/null && swapon /swapfile
  grep -q '^/swapfile' /etc/fstab || echo '/swapfile none swap sw 0 0' >> /etc/fstab
fi

if ! command -v node >/dev/null || [ "$(node -p 'process.versions.node.split(".")[0]')" -lt 24 ]; then
  curl -fsSL https://deb.nodesource.com/setup_24.x | bash -
  apt-get install -y nodejs
fi

id bright >/dev/null 2>&1 || useradd --system --home "$APP" --shell /usr/sbin/nologin bright
mkdir -p "$DATA" "$WEBROOT"

# The app folder belongs to the service user; let root's git work in it, and stop on any failure.
GIT="git -c safe.directory=$APP -C $APP"
if [ -d "$APP/.git" ]; then
  $GIT fetch -q origin main
  $GIT reset -q --hard origin/main
else
  git clone -q "$REPO" "$APP"
fi
echo "Code: $($GIT log --oneline -1)"
cd "$APP"
npm ci --include=dev --no-audit --no-fund
npm run build
chown -R bright:bright "$APP" "$DATA"

if [ ! -f "$ENVF" ]; then
  read -rp "Admin email: " AE
  read -rsp "Admin password (min 10 chars): " AP; echo
  {
    echo "NODE_ENV=production"
    echo "PORT=8787"
    echo "DATA_DIR=$DATA"
    echo "ADMIN_EMAIL=$AE"
    echo "ADMIN_PASSWORD=$AP"
    if [ -n "$DOMAIN" ]; then echo "APP_URL=https://$DOMAIN"; fi
    echo "# Paymob / Bosta / WhatsApp keys go here later (see .env.example)"
  } > "$ENVF"
  chmod 600 "$ENVF"
fi
# Only nginx talks to the app: never expose its port.
grep -q '^HOST=' "$ENVF" || echo "HOST=127.0.0.1" >> "$ENVF"

cat > /etc/systemd/system/bright.service <<UNIT
[Unit]
Description=Bright store
After=network.target

[Service]
User=bright
WorkingDirectory=$APP
EnvironmentFile=$ENVF
ExecStart=/usr/bin/npm start
Restart=always

[Install]
WantedBy=multi-user.target
UNIT
systemctl daemon-reload
systemctl enable bright >/dev/null
systemctl restart bright

# Real visitor address behind Cloudflare: trust CF-Connecting-IP only from Cloudflare's own ranges.
{
  echo "# Generated by install-vps.sh from https://www.cloudflare.com/ips/"
  for r in $(curl -fsS https://www.cloudflare.com/ips-v4) $(curl -fsS https://www.cloudflare.com/ips-v6); do echo "set_real_ip_from $r;"; done
  echo "real_ip_header CF-Connecting-IP;"
} > /etc/nginx/conf.d/cloudflare-realip.conf.new
if grep -q set_real_ip_from /etc/nginx/conf.d/cloudflare-realip.conf.new; then mv /etc/nginx/conf.d/cloudflare-realip.conf.new /etc/nginx/conf.d/cloudflare-realip.conf
else rm -f /etc/nginx/conf.d/cloudflare-realip.conf.new; echo "Could not fetch Cloudflare ranges; keeping the previous list."; fi

NAMES="_"
if [ -n "$DOMAIN" ]; then NAMES="$DOMAIN www.$DOMAIN"; fi
CERT="/etc/letsencrypt/live/$DOMAIN"

write_nginx() {
  local https="$1"
  {
    cat <<NGINX
server {
  listen 80 default_server;
  listen [::]:80 default_server;
  server_name $NAMES;
  location /.well-known/acme-challenge/ { root $WEBROOT; }
NGINX
    if [ "$https" = yes ]; then
      echo "  location / { return 301 https://\$host\$request_uri; }"
    else
      echo "  location / { include /etc/nginx/snippets/bright-proxy.conf; }"
    fi
    echo "}"
    if [ "$https" = yes ]; then
      cat <<NGINX
server {
  listen 443 ssl http2;
  listen [::]:443 ssl http2;
  server_name $NAMES;
  ssl_certificate $CERT/fullchain.pem;
  ssl_certificate_key $CERT/privkey.pem;
  ssl_protocols TLSv1.2 TLSv1.3;
  ssl_session_cache shared:SSL:10m;
  add_header Strict-Transport-Security "max-age=31536000" always;
  location / { include /etc/nginx/snippets/bright-proxy.conf; }
}
NGINX
    fi
  } > /etc/nginx/sites-available/bright
}

cat > /etc/nginx/snippets/bright-proxy.conf <<'NGINX'
client_max_body_size 10m;
proxy_pass http://127.0.0.1:8787;
proxy_set_header Host $host;
# $remote_addr is the real visitor (see conf.d/cloudflare-realip.conf); overwrite anything the client sent.
proxy_set_header X-Real-IP $remote_addr;
proxy_set_header X-Forwarded-For $remote_addr;
proxy_set_header X-Forwarded-Proto $scheme;
NGINX

HTTPS=no
if [ -n "$DOMAIN" ] && [ -f "$CERT/fullchain.pem" ]; then HTTPS=yes; fi
write_nginx "$HTTPS"
rm -f /etc/nginx/sites-enabled/default
ln -sf /etc/nginx/sites-available/bright /etc/nginx/sites-enabled/bright
nginx -t && systemctl reload nginx

# Certificate (HTTP challenge on port 80; works through the Cloudflare proxy too).
if [ -n "$DOMAIN" ] && [ "$HTTPS" = no ]; then
  if certbot certonly --webroot -w "$WEBROOT" -d "$DOMAIN" -d "www.$DOMAIN" \
       --non-interactive --agree-tos --register-unsafely-without-email \
       --deploy-hook "systemctl reload nginx"; then
    write_nginx yes
    nginx -t && systemctl reload nginx
    echo "HTTPS is on for $DOMAIN."
  else
    echo "HTTPS not issued yet: point $DOMAIN and www.$DOMAIN at this server (or its Cloudflare proxy), then re-run this script."
  fi
fi

# Firewall: SSH and the website only.
ufw allow OpenSSH >/dev/null
ufw allow 'Nginx Full' >/dev/null
ufw --force enable >/dev/null

for i in $(seq 1 30); do curl -fsS http://127.0.0.1:8787/api/health >/dev/null 2>&1 && break; sleep 1; done
curl -fsS http://127.0.0.1:8787/api/health && echo && echo "Bright is running."
